import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import {
  FORMAT_LIMITS,
  FORMAT_TARGETS,
  QUALITY,
  SCENE_KEYS,
  TIME_KEYS,
  VARIANT_SPECS,
  expectedHeight
} from "./scene-asset-config.mjs";
import {
  publishDirectoryAtomically,
  sha256Buffer,
  validateGeneratedInventory,
  validateMasterInventory
} from "./scene-asset-pipeline.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendDirectory = resolve(scriptDirectory, "..");
const sourceDirectory = resolve(frontendDirectory, "assets-source/scenes");
const assetDirectory = resolve(frontendDirectory, "src/assets/scenes");
const generatedDirectory = join(assetDirectory, "generated");
const manifestModulePath = join(assetDirectory, "manifest.generated.ts");

async function inspectMasters() {
  const inventory = [];
  for (const sceneKey of SCENE_KEYS) {
    for (const timeKey of TIME_KEYS) {
      const path = join(sourceDirectory, sceneKey, `${timeKey}.png`);
      const input = await readFile(path);
      const metadata = await sharp(input).metadata();
      inventory.push({
        sceneKey,
        timeKey,
        extension: ".png",
        width: metadata.width,
        height: metadata.height,
        channels: metadata.channels,
        relativePath: `${sceneKey}/${timeKey}.png`,
        bytes: input.length,
        sha256: sha256Buffer(input),
        path
      });
    }
  }
  return validateMasterInventory(inventory);
}

async function encodeWithinBudget(input, variant, format) {
  const target = FORMAT_TARGETS[format][variant.key];
  const hardLimit = FORMAT_LIMITS[format][variant.key];
  let lastBuffer;
  let lastQuality = QUALITY.start;
  for (let quality = QUALITY.start; quality >= QUALITY.minimum; quality -= QUALITY.step) {
    const pipeline = sharp(input).rotate().resize({ width: variant.width, withoutEnlargement: true });
    const buffer = format === "webp"
      ? await pipeline.webp({ quality, effort: 6, smartSubsample: true }).toBuffer()
      : await pipeline.jpeg({ quality, progressive: true, mozjpeg: true, chromaSubsampling: "4:2:0" }).toBuffer();
    lastBuffer = buffer;
    lastQuality = quality;
    if (buffer.length <= target) break;
  }
  if (!lastBuffer || lastBuffer.length > hardLimit) {
    throw new Error(`${format} ${variant.key} exceeds ${hardLimit} bytes at minimum quality`);
  }
  return { buffer: lastBuffer, quality: lastQuality };
}

function manifestModuleSource() {
  return `// Generated by frontend/scripts/build-scenes.mjs. Do not edit.\n` +
    `import metadata from "./generated/manifest.generated.json";\n` +
    `const urls = import.meta.glob("./generated/**/*.{webp,jpg}", { eager: true, query: "?url", import: "default" }) as Record<string, string>;\n` +
    `export const sceneAssetMetadata = metadata;\n` +
    `export const sceneAssetUrls = urls;\n`;
}

async function build() {
  const masters = await inspectMasters();
  const stagingDirectory = `${generatedDirectory}.stage-${process.pid}`;
  await rm(stagingDirectory, { recursive: true, force: true });
  await mkdir(stagingDirectory, { recursive: true });
  const entries = [];
  const masterHashes = Object.fromEntries(masters.map((entry) => [`${entry.sceneKey}/${entry.timeKey}`, entry.sha256]));
  try {
    for (const master of masters) {
      const input = await readFile(master.path);
      const sceneDirectory = join(stagingDirectory, master.sceneKey);
      await mkdir(sceneDirectory, { recursive: true });
      for (const variant of VARIANT_SPECS) {
        for (const format of ["webp", "jpg"]) {
          const { buffer, quality } = await encodeWithinBudget(input, variant, format);
          const fileName = `${master.timeKey}-${variant.width}.${format}`;
          await writeFile(join(sceneDirectory, fileName), buffer);
          entries.push({
            sceneKey: master.sceneKey,
            timeKey: master.timeKey,
            sizeKey: variant.key,
            format,
            width: variant.width,
            height: expectedHeight(variant.width),
            relativePath: `${master.sceneKey}/${fileName}`,
            bytes: buffer.length,
            sha256: sha256Buffer(buffer),
            quality
          });
        }
      }
    }
    const summary = validateGeneratedInventory(entries);
    await writeFile(join(stagingDirectory, "manifest.generated.json"), `${JSON.stringify({ version: 1, masterHashes, entries }, null, 2)}\n`, "utf8");
    await publishDirectoryAtomically({
      stagingDirectory,
      targetDirectory: generatedDirectory,
      validate: async () => validateGeneratedInventory(entries)
    });
    await writeFile(manifestModulePath, manifestModuleSource(), "utf8");
    console.log(`Scene assets generated: ${entries.length} files, WebP ${summary.webpBytes} bytes, all ${summary.totalBytes} bytes`);
  } catch (error) {
    await rm(stagingDirectory, { recursive: true, force: true });
    throw error;
  }
}

await build();
